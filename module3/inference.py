"""
Inference Engine for New Compatible Patient Windows.

Executes inference on a single 120-minute graph or temporal slice:
Graph -> Model -> Predicted Bolus Dose (Units).

IMPORTANT CLINICAL DISCLAIMER:
This model is an investigational research prototype. Predicted values are statistical
estimates and DO NOT constitute clinical dosage recommendations or medical advice.
"""

from typing import Dict, Any, Union, Optional
import os
import torch
from torch_geometric.data import Data, Batch

from module3.models.base import BaseModel
from module3.models.gcn_temporal import GCNTemporalModel
from module3.data.graph_dataset import create_dataloader, extract_temporal_sequence_from_batch
from module3.config import ModelConfig
from module3.models import build_model


class BolusPredictor:
    """
    Inference interface for predicting rapid-acting bolus dosage on new patient windows.
    """

    def __init__(self, model_type: str = "gcn_lstm", checkpoint_path: Optional[str] = None):
        self.model_type = model_type
        self.cfg = ModelConfig(model_type=model_type)
        self.model = build_model(self.cfg)

        checkpoint_path = checkpoint_path or os.path.join("data", "models", f"{model_type}_best.pt")
        if os.path.exists(checkpoint_path):
            self.model.load_checkpoint(checkpoint_path)
            self.model.eval()
            self.is_loaded = True
        else:
            self.is_loaded = False

    def predict_graph(self, pyg_graph: Data) -> Dict[str, Any]:
        """
        Predict bolus dose from a PyTorch Geometric Data object.
        """
        if not self.is_loaded:
            raise RuntimeError(f"No trained checkpoint loaded for model '{self.model_type}'.")

        loader = create_dataloader([pyg_graph], batch_size=1, shuffle=False)
        batch = next(iter(loader))

        self.model.eval()
        with torch.no_grad():
            if isinstance(self.model, GCNTemporalModel):
                pred_val = float(self.model(batch).item())
            else:
                x_seq, _ = extract_temporal_sequence_from_batch(batch)
                pred_val = float(self.model(x_seq).item())

        return {
            "predicted_bolus_dose": round(pred_val, 2),
            "units": "Insulin Units (U)",
            "model_architecture": self.model_type.upper(),
            "patient_id": getattr(pyg_graph, "patient_id", "unknown"),
            "window_id": getattr(pyg_graph, "window_id", "unknown"),
            "actual_bolus_dose": round(float(pyg_graph.y.item()), 2) if hasattr(pyg_graph, "y") else None,
            "disclaimer": (
                "FOR RESEARCH EVALUATION ONLY. This output is a statistical prediction generated by "
                "a deep learning model and DOES NOT constitute clinical medical advice or a drug prescription. "
                "Dosage calculation requires physician supervision."
            ),
        }
